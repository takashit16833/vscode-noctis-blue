'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const {
  DEFAULTS,
  readSettings,
  normalizeSettings,
  resolveImage,
  cssImage,
  mediaQueryFor,
  generateCss
} = require('../src/workbench/wallpaper');

const config = {
  enabled: true,
  image: 'https://example.org/wide.jpg',
  alternateImage: 'https://example.org/narrow.jpg',
  switchMode: 'aspect-ratio',
  maxAspectRatio: '16/10',
  maxWidth: 1400,
  tint: '#7085B0'
};

test('readSettings は壁紙画像に必要な設定だけを読む', () => {
  const actual = readSettings({ get: (_key, fallback) => fallback });
  assert.deepEqual(actual, DEFAULTS);
  assert.deepEqual(Object.keys(actual), [
    'enabled', 'image', 'alternateImage', 'switchMode',
    'maxAspectRatio', 'maxWidth', 'tint'
  ]);
});

test('無効または画像未設定なら CSS を生成しない', () => {
  assert.equal(generateCss({ enabled: false }), '');
  assert.equal(generateCss({ ...config, image: '' }), '');
  assert.equal(generateCss({ ...config, image: null }), '');
});

test('画像は画面全体に一枚描き、tint と乗算する', () => {
  const css = generateCss(config);
  assert.match(css, /linear-gradient\(#7085B0, #7085B0\)/);
  assert.match(css, /background-blend-mode: multiply, normal/);
  assert.match(css, /background-size: cover, cover/);
  assert.match(css, /url\("https:\/\/example\.org\/wide\.jpg"\)/);
  assert.doesNotMatch(css, /\.part\.(?:editor|sidebar|panel|auxiliarybar)/);
  assert.doesNotMatch(css, /backdrop-filter|color-mix|suggest-widget|sticky-widget/);
});

test('代替画像を orientation / aspect-ratio / width で切り替える', () => {
  assert.equal(mediaQueryFor(normalizeSettings({ ...config, switchMode: 'orientation' })),
    '(orientation: portrait)');
  assert.equal(mediaQueryFor(normalizeSettings({ ...config, switchMode: 'aspect-ratio' })),
    '(max-aspect-ratio: 16 / 10)');
  assert.equal(mediaQueryFor(normalizeSettings({ ...config, switchMode: 'width' })),
    '(max-width: 1400px)');

  assert.match(generateCss({ ...config, switchMode: 'orientation' }),
    /@media \(orientation: portrait\)/);
  assert.match(generateCss({ ...config, switchMode: 'width' }),
    /@media \(max-width: 1400px\)/);
  assert.doesNotMatch(generateCss({ ...config, alternateImage: '' }), /@media/);
});

test('不正な画像設定を拒否する', () => {
  assert.throws(() => normalizeSettings({ ...config, enabled: 'yes' }), /enabled/);
  assert.throws(() => normalizeSettings({ ...config, image: 42 }), /image/);
  assert.throws(() => normalizeSettings({ ...config, alternateImage: [] }), /alternateImage/);
  assert.throws(() => normalizeSettings({ ...config, switchMode: 'height' }), /switchMode/);
  assert.throws(() => normalizeSettings({ ...config, maxAspectRatio: '0/10' }), /maxAspectRatio/);
  assert.throws(() => normalizeSettings({ ...config, maxWidth: 0 }), /maxWidth/);
  assert.throws(() => normalizeSettings({ ...config, tint: 'white' }), /tint/);
});

test('ローカル画像と相対パスを安全に URL 化する', () => {
  assert.match(resolveImage('/tmp/a b.png').url,
    /^vscode-file:\/\/vscode-app\/tmp\/a%20b.png$/);
  assert.match(resolveImage('./image.png', { workspaceDirectory: '/tmp/project' }).url,
    /project\/image\.png$/);
  assert.throws(() => resolveImage('./image.png'), /作業フォルダー/);
  assert.throws(() => resolveImage('javascript:alert(1)'), /画像には/);
  assert.throws(() => resolveImage('https://example.org/\n'), /使用できない/);
});

test('CSS URL をエスケープし、HTML 混入を拒否する', () => {
  assert.equal(cssImage('https://example.org/a"b.png'),
    'url("https://example.org/a\\\"b.png")');
  assert.throws(() => cssImage('</style>'), /使用できない/);
});

test('resolveUrl と rootSelector をプレビュー用に差し替えられる', () => {
  const css = generateCss(config, {
    rootSelector: '.preview-root',
    resolveUrl: value => 'preview://' + encodeURIComponent(value)
  });
  assert.match(css, /^\/\* Generated by Noctis Blue/);
  assert.match(css, /\.preview-root \{/);
  assert.match(css, /preview:\/\/https%3A%2F%2Fexample\.org%2Fwide\.jpg/);
});
